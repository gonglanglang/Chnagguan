const staticChoice = (stem, options, answerIndex, analysis, tags = []) => ({
  questionMode: 'STATIC',
  questionFormat: 'SINGLE_CHOICE',
  stem,
  options,
  answer: { index: answerIndex },
  analysis,
  tags,
});

const paramChoice = (vars, stemTpl, ansExpr, wrongExprs, analysis, tags = []) => ({
  questionMode: 'DYNAMIC_TEMPLATE',
  questionFormat: 'SINGLE_CHOICE',
  stem: stemTpl,
  analysis,
  tags,
  templateRule: {
    type: 'PARAM_TEMPLATE',
    vars,
    stemTpl,
    ansExpr,
    wrongExprs,
  },
});

const staticEssay = (stem, referenceAnswer, analysis, tags = []) => ({
  questionMode: 'STATIC',
  questionFormat: 'ESSAY',
  stem,
  options: [],
  answer: { text: referenceAnswer },
  analysis,
  tags,
});

